/** iOS splash screens generated by scripts/generate-icons.mjs (current iPhone sizes, section 9.3). */
function splashLinks() {
  const sizes: [number, number, number][] = [
    [430, 932, 3],
    [393, 852, 3],
    [428, 926, 3],
    [390, 844, 3],
    [375, 812, 3],
    [414, 896, 2],
    [375, 667, 2],
  ];
  return sizes.map(([w, h, r]) => ({
    url: `/splash/splash-${w * r}x${h * r}.png`,
    media: `(device-width: ${w}px) and (device-height: ${h}px) and (-webkit-device-pixel-ratio: ${r}) and (orientation: portrait)`,
  }));
}

export default function RootLayout({ children }: { children: React.ReactNode }) {
  return (
    <html lang="en" suppressHydrationWarning>
      <head>
        {/* biome-ignore lint/security/noDangerouslySetInnerHtml: static theme boot script avoids a theme flash */}
        <script dangerouslySetInnerHTML={{ __html: THEME_BOOT }} />
      </head>
      <body>
        <Providers>{children}</Providers>
      </body>
    </html>
  );
}
